"""Make the AI-generated C skeleton actually compile.

The C-skeleton exporter emits pseudocode labels, references ``Rte_*`` APIs and
``l_*`` variables that have no declarations, and sometimes non-C text.  This
module:

1. generates ``Rte_Type.h`` (Std_Types) and ``Rte_<SWC>.h`` (declarations for
   every ``Rte_*`` / helper identifier found in the skeleton);
2. generates ``Rte_Stubs.c`` with matching default definitions so a test binary
   can link;
3. runs ``gcc -std=c99 -fsyntax-only`` in a loop: missing symbols are
   declared as TODO(design) placeholders, and only statements that still fail
   become ``/* TODO(design): <original> */`` (trace comments are kept);
4. reports "N of M statements kept as C, K stubbed".
"""

