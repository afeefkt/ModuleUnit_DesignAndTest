    "ceil", "ceilf", "round", "roundf", "trunc", "truncf", "fmod", "fmodf", "pow", "powf",
    "exp", "expf", "log", "logf", "sin", "sinf", "cos", "cosf", "tan", "tanf", "atan", "atanf",
