"""Make the AI-generated C skeleton actually compile.

The C-skeleton exporter emits pseudocode labels, references ``Rte_*`` APIs and
``l_*`` variables that have no declarations, and sometimes non-C text.  This
module:

1. generates ``Rte_Type.h`` (Std_Types) and ``Rte_<SWC>.h`` (declarations for
   every ``Rte_*`` / helper identifier found in the skeleton);
2. generates ``Rte_Stubs.c`` with matching default definitions so a test binary
   can link;
3. runs ``gcc -std=c99 -fsyntax-only`` in a loop: missing symbols are
   declared as TODO(design) placeholders, and only statements that still fail
   become ``/* TODO(design): <original> */`` (trace comments are kept);
4. reports "N of M statements kept as C, K stubbed".
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from mudmut_core import toolchain

_KEYWORDS = {
    "if", "else", "for", "while", "switch", "case", "default", "return",
    "sizeof", "do", "break", "continue", "goto", "static", "void", "int",
    "char", "unsigned", "signed", "float", "double", "long", "short",
    "typedef", "struct", "union", "enum", "const", "volatile",
}

_RTE_CALL_RE = re.compile(r"\b(Rte_[A-Za-z0-9_]+)\b")
_CALL_RE = re.compile(r"\b([A-Za-z_][A-Za-z0-9_]*)\s*\(")
_VAR_RE = re.compile(r"\b(l_[A-Za-z0-9_]+)\b")
# GCC quotes names with ‘ ’ (U+2018/2019) in UTF-8 locales and ' ' under LC_ALL=C.
_IMPLICIT_DECL_RE = re.compile(
    "implicit declaration of function ['\"‘](\\w+)['\"’]"
)


